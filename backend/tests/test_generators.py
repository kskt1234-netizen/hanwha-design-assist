from app.generators.ddl import generate_ddl
from app.generators.mermaid import generate_mermaid
from app.llm.mock import feature_name, split_requirements
from app.review.rules import run_rules
from app.schemas import Attribute, Cardinality, DesignState, Entity, Feature, Relationship, Requirement


def _state() -> DesignState:
    return DesignState(
        requirements=[Requirement(code="REQ-001", text="품목을 등록한다"), Requirement(code="REQ-002", text="창고를 조회한다")],
        features=[Feature(code="FN-001", name="품목 등록", requirement_codes=["REQ-001"])],
        entities=[
            Entity(table_name="item", logical_name="품목", feature_codes=["FN-001"], attributes=[
                Attribute(name="id", data_type="BIGINT", nullable=False, is_pk=True),
                Attribute(name="item_code", logical_name="품목코드", data_type="VARCHAR", length=30, is_unique=True),
            ]),
            Entity(table_name="inventory", attributes=[
                Attribute(name="id", data_type="BIGINT", is_pk=True),
                Attribute(name="item_id", data_type="INTEGER"),
            ]),
            Entity(table_name="order", attributes=[Attribute(name="qty", data_type="INTEGER")]),
        ],
        relationships=[
            Relationship(from_table="inventory", to_table="item", fk_column="item_id"),
            Relationship(from_table="inventory", to_table="warehouse", fk_column="warehouse_id"),
            Relationship(from_table="item", to_table="order", fk_column="qty", cardinality=Cardinality.MANY_TO_MANY),
        ],
    )


def test_rules_find_each_problem():
    codes = {(i.rule_code, i.target_code) for i in run_rules(_state())}
    assert ("R01", "REQ-002") in codes  # 기능 없는 요구사항
    assert ("R04", "inventory") in codes  # 기능 없는 테이블
    assert ("R05", "order") in codes  # PK 없음 + 예약어
    assert ("R06", "inventory.item_id") in codes  # FK 타입 불일치
    assert ("R06", "inventory.warehouse_id") in codes  # 없는 테이블 참조
    assert ("R07", "item.qty") in codes  # N:M


def test_ddl_and_mermaid():
    ddl = generate_ddl(_state())
    assert "item_code VARCHAR(30) UNIQUE" in ddl
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL" in ddl
    assert "COMMENT ON COLUMN item.item_code IS '품목코드';" in ddl
    assert "FOREIGN KEY (item_id) REFERENCES item (id)" in ddl
    mm = generate_mermaid(_state())
    assert "item ||--o{ inventory" in mm
    assert 'INTEGER item_id FK' in mm


def test_mock_parsing():
    items = split_requirements("# 제목\n1. 관리자는 품목 정보를 등록하고 수정할 수 있어야 한다.\n- 짧음\n")
    assert items == ["관리자는 품목 정보를 등록하고 수정할 수 있어야 한다."]
    assert feature_name("사용자는 품목별, 창고별 현재고를 조회할 수 있어야 한다.") == "창고별 현재고 조회"
