"""DataModel -> PostgreSQL DDL. LLM이 아니라 코드가 만들기 때문에 수정 사항이 그대로 반영된다."""
from app.schemas import Attribute, DesignState, Entity

LENGTH_TYPES = {"VARCHAR", "CHAR", "CHARACTER VARYING", "NUMERIC", "DECIMAL"}


def _sql_literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def column_type(a: Attribute) -> str:
    t = a.data_type.upper().strip()
    if a.length and t in LENGTH_TYPES and "(" not in t:
        t = f"{t}({a.length})"
    return t


def _column_def(e: Entity, a: Attribute) -> str:
    pk_cols = [x for x in e.attributes if x.is_pk]
    parts = [a.name, column_type(a)]
    if a.is_pk and len(pk_cols) == 1 and a.data_type.upper() in {"BIGINT", "INTEGER", "INT"}:
        parts.append("GENERATED BY DEFAULT AS IDENTITY")
    if not a.nullable or a.is_pk:
        parts.append("NOT NULL")
    if a.default:
        parts.append(f"DEFAULT {a.default}")
    if a.is_unique and not a.is_pk:
        parts.append("UNIQUE")
    return " ".join(parts)


def create_table(e: Entity) -> str:
    lines = [_column_def(e, a) for a in e.attributes]
    pk_cols = [a.name for a in e.attributes if a.is_pk]
    if pk_cols:
        lines.append(f"CONSTRAINT pk_{e.table_name} PRIMARY KEY ({', '.join(pk_cols)})")
    body = ",\n    ".join(lines)
    sql = f"CREATE TABLE {e.table_name} (\n    {body}\n);"
    comments = []
    if e.logical_name:
        comments.append(f"COMMENT ON TABLE {e.table_name} IS {_sql_literal(e.logical_name)};")
    for a in e.attributes:
        if a.logical_name:
            comments.append(f"COMMENT ON COLUMN {e.table_name}.{a.name} IS {_sql_literal(a.logical_name)};")
    return "\n".join([sql, *comments])


def generate_ddl(state: DesignState) -> str:
    out = ["-- 자동 생성된 DDL 초안 (PostgreSQL)", ""]
    for e in state.entities:
        out.append(create_table(e))
        out.append("")
    entities = {e.table_name: e for e in state.entities}
    for r in state.relationships:
        parent = entities.get(r.to_table)
        parent_pk = [a.name for a in parent.attributes if a.is_pk] if parent else ["id"]
        out.append(
            f"ALTER TABLE {r.from_table} ADD CONSTRAINT fk_{r.from_table}_{r.fk_column} "
            f"FOREIGN KEY ({r.fk_column}) REFERENCES {r.to_table} ({', '.join(parent_pk)}) "
            f"ON DELETE {r.on_delete};"
        )
        out.append(f"CREATE INDEX ix_{r.from_table}_{r.fk_column} ON {r.from_table} ({r.fk_column});")
    return "\n".join(out).rstrip() + "\n"
